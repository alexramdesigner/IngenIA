import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const selection = {
  phone: 'fill/device-mobile-fill', qr: 'fill/qr-code-fill', slides: 'fill/presentation-fill',
  product: 'duotone/clipboard-text-duotone', techlead: 'duotone/cpu-duotone', aideveloper: 'duotone/robot-duotone',
  qa: 'duotone/shield-check-duotone', security: 'duotone/shield-checkered-duotone', devops: 'duotone/gear-six-duotone',
  email: 'fill/envelope-simple-fill', notes: 'fill/notepad-fill', trophy: 'fill/trophy-fill', chat: 'fill/chat-dots-fill', folder: 'fill/folder-fill', chart: 'fill/chart-bar-fill',
  person: 'fill/user-fill', calendar: 'fill/calendar-blank-fill', workshop: 'fill/sparkle-fill', rocket: 'fill/rocket-launch-fill', code: 'fill/code-fill',
  home: 'fill/house-fill', activities: 'fill/squares-four-fill', target: 'fill/target-fill', ranking: 'fill/ranking-fill', hourglass: 'fill/hourglass-medium-fill',
  gauge: 'fill/gauge-fill', teams: 'fill/users-three-fill', megaphone: 'fill/megaphone-fill', teacher: 'fill/chalkboard-teacher-fill', projector: 'fill/projector-screen-fill',
  sidebar: 'regular/sidebar-simple', menu: 'regular/list', logout: 'fill/sign-out-fill', pause: 'fill/pause-fill', play: 'fill/play-fill', extend: 'fill/plus-circle-fill',
  advance: 'fill/skip-forward-fill', iterate: 'fill/arrows-clockwise-fill', reopen: 'fill/arrow-counter-clockwise-fill', finish: 'fill/flag-checkered-fill', lightning: 'fill/lightning-fill', warning: 'fill/warning-fill', check: 'fill/check-circle-fill', trash: 'fill/trash-fill', live: 'fill/broadcast-fill',
  caret: 'bold/caret-right-bold', monitor: 'regular/presentation', qrline: 'regular/qr-code', back: 'regular/arrow-left', forward: 'regular/arrow-right', expand: 'regular/arrows-out', collapse: 'regular/arrows-in'
};
const icons = Object.fromEntries(Object.entries(selection).map(([key, file]) => {
  const svg = readFileSync(`node_modules/@phosphor-icons/core/assets/${file}.svg`, 'utf8').trim();
  return [key, svg.replace('<svg ', `<svg class="ui-icon" data-ph-icon="${key}" width="22" height="22" aria-hidden="true" focusable="false" `)];
}));
writeFileSync('packages/ui/icons.mjs', `// Generated by npm run icons from @phosphor-icons/core (MIT).\nconst icons = ${JSON.stringify(icons, null, 2)};\nexport function icon(name) { return icons[name] ?? ''; }\n`);
for (const file of ['apps/participant/index.html','apps/projector/index.html']) {
  let html = readFileSync(file,'utf8');
  html = html.replace(/<svg\b([^>]*)data-ph-icon="([a-z]+)"[^>]*>[\s\S]*?<\/svg>/g,(svg, before, name) => {
    const classes = /class="([^"]*)"/.exec(svg)?.[1] ?? 'ui-icon';
    return icons[name].replace('class="ui-icon"',`class="${classes}"`);
  });
  writeFileSync(file,html);
}
mkdirSync('packages/ui/licenses',{recursive:true});
copyFileSync('node_modules/@phosphor-icons/core/LICENSE','packages/ui/licenses/phosphor-MIT.txt');
console.log(`Generados ${Object.keys(icons).length} iconos locales.`);
